#!/usr/bin/env python3
"""
Convert an 8x16 PSF console font (PSF1 or PSF2, optionally gzipped) to C:
a 256-entry glyph table indexed by Latin-1 byte value, using the font's
Unicode table to find each glyph. Missing characters become '?'.

usage: tools/psf2c.py /usr/share/consolefonts/Lat15-VGA16.psf.gz > font8x16.c
"""
import gzip
import struct
import sys


def load_psf(path):
    data = open(path, "rb").read()
    if data[:2] == b"\x1f\x8b":
        data = gzip.decompress(data)
    if data[:2] == b"\x36\x04":                       # PSF1
        mode, height = data[2], data[3]
        count = 512 if mode & 1 else 256
        glyphs = [data[4 + i * height: 4 + (i + 1) * height] for i in range(count)]
        width, table = 8, None
        if mode & 2:                                  # unicode table (UCS-2)
            table, pos = [], 4 + count * height
            for _ in range(count):
                cps = []
                while True:
                    (v,) = struct.unpack_from("<H", data, pos); pos += 2
                    if v == 0xFFFF:
                        break
                    if v != 0xFFFE:
                        cps.append(v)
                table.append(cps)
    elif data[:4] == b"\x72\xb5\x4a\x86":             # PSF2
        _, _, hdrsize, flags, count, size, height, width = struct.unpack_from("<8I", data)
        glyphs = [data[hdrsize + i * size: hdrsize + (i + 1) * size] for i in range(count)]
        table = None
        if flags & 1:                                 # unicode table (UTF-8)
            table, pos = [], hdrsize + count * size
            for _ in range(count):
                end = data.index(b"\xff", pos)
                entry = data[pos:end].split(b"\xfe")[0]
                table.append([ord(c) for c in entry.decode("utf-8")])
                pos = end + 1
    else:
        sys.exit("not a PSF font")
    if width != 8 or height != 16:
        sys.exit(f"need an 8x16 font, this is {width}x{height}")
    return glyphs, table


def main():
    glyphs, table = load_psf(sys.argv[1])
    by_cp = {}
    if table:
        for i, cps in enumerate(table):
            for cp in cps:
                by_cp.setdefault(cp, i)
    else:
        by_cp = {i: i for i in range(min(256, len(glyphs)))}

    blank = bytes(16)
    out = [f"/* 8x16 console font, generated by tools/psf2c.py from\n"
           f" * {sys.argv[1].split('/')[-1]} (Linux console-setup fonts: public domain).\n"
           f" * Indexed by Latin-1 byte value; one byte per row, MSB = leftmost pixel. */\n\n"
           "const unsigned char font8x16[256][16] = {\n"]
    for b in range(256):
        if b < 0x20 or 0x7F <= b < 0xA0:
            g = blank                                 # control characters
        else:
            g = glyphs[by_cp.get(b, by_cp.get(ord("?"), 0))]
        out.append("\t{" + ",".join(f"0x{x:02x}" for x in g) + "},"
                   + (f"\t/* {chr(b)!r} */" if 0x20 <= b < 0x7F else "") + "\n")
    out.append("};\n")
    sys.stdout.write("".join(out))


if __name__ == "__main__":
    main()
